package switchstatement;

public class Days {
	public static void main(String args[]) {
		String day="mon";
		switch(day) {	
		case"sun" :System.out.println("sun");
		break;
		
		case"mon" :System.out.println("mon");
		break;
		
		case"tue" :System.out.println("tue");
		break;
		
		case"wed" :System.out.println("tue");
		break;
		
		case"thu" :System.out.println("thu");
		break;
		
		case"fri" :System.out.println("fri");
		break;
		
		case"sat" :System.out.println("sat");
		break;
		
		default : System.out.println("invalid values");
		
		}
	}

}
